def printed(value: float, text: str) -> str:
    """Round a value to the number of decimals of a printed number."""
    decimals = len(text.split(".")[1]) if "." in text else 0
    return f"{round(value, decimals) + 0.0:.{decimals}f}"


def test_counts(items, responses):
    conditions = read_jsonl("conditions.jsonl")
    assert len(items) == 194
    assert len({row["item_id"] for row in items}) == 194
    assert len({row["paper"]["paper_family_id"] for row in items}) == 194
    assert len(conditions) == 388
    assert Counter(row["condition"] for row in conditions) == {
        "answer_present": 194,
        "answer_absent": 194,
    }
    assert len(responses) == 9312
    assert len({row["trial_id"] for row in responses}) == 9312
    assert set(Counter(row["item_id"] for row in responses).values()) == {48}
    cell = Counter((r["item_id"], r["model"], r["condition"]) for r in responses)
    assert len(cell) == 194 * 8 * 2 and set(cell.values()) == {3}
    assert {row["model"] for row in responses} == set(paper_release.MODEL_ORDER)
    assert {row["reasoning_effort"] for row in responses} == {"high"}
    assert {row["status"] for row in items} == {"machine_accepted_unverified"}
    assert sum(len(row["distractors"]) for row in items) == 776


