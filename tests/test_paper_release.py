def test_committed_results_match_the_paper():
    summary = json.loads((RESULTS / "summary.json").read_text())
    assert summary["questions"] == 194 and summary["responses"] == 9312
    assert summary["invalid_responses"] == 107
    shifts = {
        row["model_id"]: row
        for row in csv.DictReader((RESULTS / "condition-shifts.csv").open())
    }
    for model, expected in PAPER_CONDITION_TABLE.items():
        row = shifts[model]
        present, absent = (
            100 * float(row["present_abstention"]),
            100 * float(row["absent_abstention"]),
        )
        assert printed(present, expected[0]) == expected[0], model
        assert printed(absent, expected[1]) == expected[1], model
        # The paper prints the shift as the difference of the two rounded rates.
        assert (
            printed(float(expected[1]) - float(expected[0]), expected[2]) == expected[2]
        ), model
        exact_shift = printed(100 * float(row["shift"]), expected[2])
        assert exact_shift == EXACT_WHERE_PAPER_ROUNDS.get(
            (model, "shift"), expected[2]
        )
        assert printed(100 * float(row["shift_ci_low"]), expected[3]) == expected[3], (
            model
        )
        assert printed(100 * float(row["shift_ci_high"]), expected[4]) == expected[4], (
            model
        )
        assert printed(float(row["permutation_p"]), expected[5]) == expected[5], model
        exact_holm = printed(float(row["holm_p"]), expected[6])
        assert exact_holm == EXACT_WHERE_PAPER_ROUNDS.get((model, "holm"), expected[6])
    pooled = summary["pooled_shift_test"]
    assert f"{100 * pooled['mean_shift_over_models']:.2f}" == "5.05"
    assert pooled["questions"] == 194
    lowest, highest = summary["present_abstention_range"]
    assert (f"{100 * lowest:.1f}", f"{100 * highest:.1f}") == ("0.0", "63.0")
    metrics = {
        row["model_id"]: row for row in csv.DictReader((RESULTS / "metrics.csv").open())
    }
    for model, expected in PAPER_METRIC_TABLE.items():
        values = tuple(
            f"{float(metrics[model][f'{m}_pooled']):.3f}"
            for m in paper_tables.PAPER_METRICS
        )
        assert values == expected, model


