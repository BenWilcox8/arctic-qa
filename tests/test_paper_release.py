def test_manifest_binds_the_files():
    manifest = json.loads((DATA / "MANIFEST.json").read_text())
    for name, digest in manifest["files"].items():
        assert hashlib.sha256((DATA / name).read_bytes()).hexdigest() == digest, name
    assert manifest["counts"]["responses"] == 9312
    assert manifest["counts"]["condition_renderings"] == 388


def test_no_private_material_is_released():
    for path in DATA.rglob("*"):
        if path.is_file():
            text = path.read_text(encoding="utf-8")
            assert "/home/" not in text and "/mnt/" not in text, path
            assert "receipt_file" not in text and "request_key" not in text, path
    item_keys = {key for row in read_jsonl("items.jsonl") for key in row}
    paper_keys = {key for row in read_jsonl("items.jsonl") for key in row["paper"]}
    assert item_keys.isdisjoint({"evidence", "source", "construction_roles"})
    assert paper_keys == {"doi", "title", "year", "paper_family_id"}
    assert all(
        path.stat().st_size < 50 * 1024 * 1024
        for path in DATA.rglob("*")
        if path.is_file()
    )


